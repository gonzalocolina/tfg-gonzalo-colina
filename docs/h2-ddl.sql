    inter_pod_card_definition_id BIGINT,
    card_name VARCHAR(120) NOT NULL,
    card_category VARCHAR(20) NOT NULL,
    hp_max INTEGER NOT NULL DEFAULT 0,
    hp_current INTEGER NOT NULL DEFAULT 0,
    threat_max INTEGER NOT NULL DEFAULT 0,
    threat_current INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    image_path VARCHAR(500),
    image_content_type VARCHAR(120),
    CONSTRAINT fk_event_inter_pod_card_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_inter_pod_card_pod FOREIGN KEY (pod_id) REFERENCES pods (id),
    CONSTRAINT fk_event_inter_pod_card_source_group FOREIGN KEY (source_group_id) REFERENCES player_table (id),
    CONSTRAINT fk_event_inter_pod_card_definition FOREIGN KEY (inter_pod_card_definition_id) REFERENCES inter_pod_card_definitions (id)
);
