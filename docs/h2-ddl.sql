-- DDL reconstruido a partir de las entidades JPA del backend.
-- Basado en la estructura actual del modelo, no en datos existentes.

DROP TABLE IF EXISTS event_inter_pod_card;
DROP TABLE IF EXISTS event_logs;
DROP TABLE IF EXISTS invitations;
DROP TABLE IF EXISTS event_villain;
DROP TABLE IF EXISTS player_table;
DROP TABLE IF EXISTS pods;
DROP TABLE IF EXISTS events;
DROP TABLE IF EXISTS inter_pod_card_definitions;
DROP TABLE IF EXISTS villain_definitions;
DROP TABLE IF EXISTS event_organizers;

CREATE TABLE event_organizers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    username VARCHAR(60) NOT NULL,
    email VARCHAR(120),
    password_hash VARCHAR(120),
    role VARCHAR(30) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_event_organizers_username UNIQUE (username),
    CONSTRAINT uk_event_organizers_email UNIQUE (email)
);

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    name VARCHAR(120) NOT NULL,
    configured_player_count INTEGER NOT NULL,
    time_limit_minutes INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    result VARCHAR(30),
    event_code VARCHAR(20) NOT NULL,
    organizer_id BIGINT NOT NULL,
    villain_hp_max INTEGER NOT NULL DEFAULT 0,
    villain_hp_current INTEGER NOT NULL DEFAULT 0,
    scheme_threat_target INTEGER NOT NULL DEFAULT 0,
    scheme_threat_current INTEGER NOT NULL DEFAULT 0,
    timer_total_seconds INTEGER NOT NULL DEFAULT 0,
    timer_remaining_seconds INTEGER NOT NULL DEFAULT 0,
    timer_status VARCHAR(20) NOT NULL,
    finish_cause VARCHAR(40),
    total_reported_villain_damage INTEGER NOT NULL DEFAULT 0,
    villain_half_hp_notified BOOLEAN NOT NULL DEFAULT FALSE,
    villain_quarter_hp_notified BOOLEAN NOT NULL DEFAULT FALSE,
    threat_half_notified BOOLEAN NOT NULL DEFAULT FALSE,
    threat_three_quarter_notified BOOLEAN NOT NULL DEFAULT FALSE,
    timer_thirty_minutes_notified BOOLEAN NOT NULL DEFAULT FALSE,
    timer_fifteen_minutes_notified BOOLEAN NOT NULL DEFAULT FALSE,
    timer_five_minutes_notified BOOLEAN NOT NULL DEFAULT FALSE,
    timer_started_at TIMESTAMP WITH TIME ZONE,
    timer_paused_at TIMESTAMP WITH TIME ZONE,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_events_event_code UNIQUE (event_code),
    CONSTRAINT fk_events_organizer FOREIGN KEY (organizer_id) REFERENCES event_organizers (id)
);

CREATE TABLE villain_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20) NOT NULL,
    hp_rule_type VARCHAR(20) NOT NULL,
    hp_rule_value INTEGER NOT NULL,
    threat_rule_type VARCHAR(20) NOT NULL,
    threat_rule_value INTEGER NOT NULL,
    owner_id BIGINT,
    CONSTRAINT fk_villain_definitions_owner FOREIGN KEY (owner_id) REFERENCES event_organizers (id)
);

CREATE TABLE inter_pod_card_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20) NOT NULL,
    card_category VARCHAR(20) NOT NULL,
    default_hp_max INTEGER NOT NULL DEFAULT 0,
    default_threat_max INTEGER NOT NULL DEFAULT 0,
    default_status VARCHAR(20) NOT NULL,
    image_path VARCHAR(500),
    image_content_type VARCHAR(120),
    owner_id BIGINT,
    CONSTRAINT fk_inter_pod_card_definitions_owner FOREIGN KEY (owner_id) REFERENCES event_organizers (id)
);

CREATE TABLE event_villain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    villain_definition_id BIGINT,
    name VARCHAR(120) NOT NULL,
    type VARCHAR(20) NOT NULL,
    hp_rule_type VARCHAR(20) NOT NULL,
    hp_rule_value INTEGER NOT NULL,
    threat_rule_type VARCHAR(20) NOT NULL,
    threat_rule_value INTEGER NOT NULL,
    CONSTRAINT uk_event_villain_event UNIQUE (event_id),
    CONSTRAINT fk_event_villain_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_villain_definition FOREIGN KEY (villain_definition_id) REFERENCES villain_definitions (id)
);

CREATE TABLE pods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    name VARCHAR(80) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_pods_event FOREIGN KEY (event_id) REFERENCES events (id)
);

CREATE TABLE player_table (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    pod_id BIGINT,
    identifier VARCHAR(40) NOT NULL,
    player_count INTEGER NOT NULL,
    representative_code VARCHAR(16) NOT NULL,
    observer_code VARCHAR(16) NOT NULL,
    CONSTRAINT uk_player_table_representative_code UNIQUE (representative_code),
    CONSTRAINT uk_player_table_observer_code UNIQUE (observer_code),
    CONSTRAINT fk_player_table_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_player_table_pod FOREIGN KEY (pod_id) REFERENCES pods (id)
);

CREATE TABLE invitations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    invited_by_user_id BIGINT,
    status VARCHAR(20) NOT NULL,
    responsibilities VARCHAR(100) NOT NULL,
    CONSTRAINT fk_invitations_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_invitations_user FOREIGN KEY (user_id) REFERENCES event_organizers (id),
    CONSTRAINT fk_invitations_invited_by FOREIGN KEY (invited_by_user_id) REFERENCES event_organizers (id)
);

CREATE TABLE event_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    group_id BIGINT,
    actor_id BIGINT,
    reverted_log_id BIGINT,
    action_type VARCHAR(40) NOT NULL,
    previous_value VARCHAR(255),
    new_value VARCHAR(255),
    notes VARCHAR(500),
    CONSTRAINT fk_event_logs_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_event_logs_group FOREIGN KEY (group_id) REFERENCES player_table (id),
    CONSTRAINT fk_event_logs_actor FOREIGN KEY (actor_id) REFERENCES event_organizers (id),
    CONSTRAINT fk_event_logs_reverted_log FOREIGN KEY (reverted_log_id) REFERENCES event_logs (id)
);

CREATE TABLE event_inter_pod_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    event_id BIGINT NOT NULL,
    pod_id BIGINT NOT NULL,
